package com.springMVC.entity;

public class BaySize {
     private String deckRows;
     private String deckTiers;
     private String holdRows;
     private String holdTiers;
	public String getDeckRows() {
		return deckRows;
	}
	public void setDeckRows(String deckRows) {
		this.deckRows = deckRows;
	}
	public String getDeckTiers() {
		return deckTiers;
	}
	public void setDeckTiers(String deckTiers) {
		this.deckTiers = deckTiers;
	}
	public String getHoldRows() {
		return holdRows;
	}
	public void setHoldRows(String holdRows) {
		this.holdRows = holdRows;
	}
	public String getHoldTiers() {
		return holdTiers;
	}
	public void setHoldTier(String holdTiers) {
		this.holdTiers = holdTiers;
	}
     
}
